/// The answer to a feature report read, for the controller at `address`.
pub fn feature(number: u8, address: [u8; 6]) -> Option<Vec<u8>> {
    // Addresses go over the wire lowest byte first.
    let mut reversed = address;
    reversed.reverse();
    match number {
        0x02 => Some(CALIBRATION.to_vec()),
        0xa3 => Some(FIRMWARE.to_vec()),
        // Its own address.
        0x81 => Some([&[0x81][..], &reversed].concat()),
        // Pairing: its own address, a fixed class, and the host it is paired
        // with, which on a cable is none.
        0x12 => Some([&[0x12][..], &reversed, &[0x08, 0x25, 0x00], &[0; 6]].concat()),
        _ => None,
    }
}

/// Rumble from output report 0x05: `(strong, weak)`, when the report sets it.
/// The left motor is the heavy one.
pub fn rumble(report: &[u8]) -> Option<(u16, u16)> {
    const SETS_MOTORS: u8 = 0x01;
    match report {
        [0x05, flags, _, _, weak, strong, ..] if flags & SETS_MOTORS != 0 => {
            Some((u16::from(*strong) * 257, u16::from(*weak) * 257))
        }
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_descriptor_declares_what_the_reports_are() {
        // Input 0x01 is 63 bytes after its id, output 0x05 31.
        let d = DESCRIPTOR;
        assert_eq!(d.len(), 507);
        assert_eq!(&d[..6], &[0x05, 0x01, 0x09, 0x05, 0xa1, 0x01]);
        assert!(d.windows(4).any(|w| w == [0x85, 0x05, 0x09, 0x22]));
    }

    #[test]
    fn a_controller_at_rest_reads_as_one() {
        // Compared with a report from the real device lying still.
        let r = input_report(&PadState::default(), 0, 0);
        assert_eq!(&r[..10], &[0x01, 0x80, 0x80, 0x80, 0x80, 0x08, 0, 0, 0, 0]);
        assert_eq!(r[30], 0x1b);
    }

    #[test]
    fn every_button_lands_on_its_bit() {
        let all = PadState {
            buttons: !(button::DPAD_UP
                | button::DPAD_DOWN
                | button::DPAD_LEFT
                | button::DPAD_RIGHT),
            ..PadState::default()
        };
        let r = input_report(&all, 0, 0);
        assert_eq!((r[5], r[6], r[7]), (0xf8, 0xff, 0x01));
    }

    #[test]
    fn the_hat_goes_round_clockwise_from_up() {
        use button::*;
        for (held, value) in [
            (DPAD_UP, 0),
            (DPAD_UP | DPAD_RIGHT, 1),
            (DPAD_RIGHT, 2),
            (DPAD_DOWN | DPAD_RIGHT, 3),
            (DPAD_DOWN, 4),
            (DPAD_DOWN | DPAD_LEFT, 5),
            (DPAD_LEFT, 6),
            (DPAD_UP | DPAD_LEFT, 7),
            (DPAD_UP | DPAD_DOWN, 8),
        ] {
            assert_eq!(hat(held), value, "{held:#x}");
        }
    }

    #[test]
    fn sticks_and_triggers_reach_both_ends() {
        let pushed = PadState {
            left_x: i16::MIN,
            left_y: i16::MAX,
            right_trigger: u16::MAX,
            ..PadState::default()
        };
        let r = input_report(&pushed, 63, 0x1234);
        assert_eq!((r[1], r[2], r[9]), (0, 255, 255));
        assert_eq!(r[6] & 0x08, 0x08);
        assert_eq!(r[7] >> 2, 63);
        assert_eq!(&r[10..12], &[0x34, 0x12]);
    }

    #[test]
    fn reports_carry_the_address_they_were_given() {
        let address = [0xa0, 0xab, 0x51, 0x0b, 0xad, 0x42];
        assert_eq!(
            feature(0x81, address).unwrap(),
            [0x81, 0x42, 0xad, 0x0b, 0x51, 0xab, 0xa0]
        );
        let pairing = feature(0x12, address).unwrap();
        assert_eq!(pairing.len(), 16);
        assert_eq!(&pairing[1..7], &[0x42, 0xad, 0x0b, 0x51, 0xab, 0xa0]);
        assert_eq!(feature(0x02, address).unwrap().len(), 37);
        assert_eq!(feature(0xa3, address).unwrap().len(), 49);
        assert_eq!(feature(0x04, address), None);
    }

    #[test]
    fn rumble_is_read_only_when_the_report_sets_it() {
        assert_eq!(
            rumble(&[0x05, 0x07, 0x04, 0, 0x40, 0xff, 0, 0, 0xff]),
            Some((0xffff, 0x4040))
        );
        // Lights only.
        assert_eq!(rumble(&[0x05, 0x02, 0x04, 0, 0x40, 0xff]), None);
        assert_eq!(rumble(&[0x11, 0xff]), None);
    }
}
