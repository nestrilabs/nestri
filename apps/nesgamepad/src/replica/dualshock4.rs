/// Input report 0x01, the one the device sends continuously.
pub const INPUT_LEN: usize = 64;

/// How often the device sends it. A real one never goes quiet while plugged
/// in, and software that reads it by hand counts on the counter and the
/// sensor clock moving.
pub const REPORT_EVERY: std::time::Duration = std::time::Duration::from_millis(4);

/// The sensor clock ticks every 16/3 µs.
pub fn sensor_ticks(elapsed: std::time::Duration) -> u16 {
    (elapsed.as_micros() * 3 / 16) as u16
}

/// A stick axis in the device's byte, from the wire's full range. Both have
/// down as positive.
fn stick(value: i16) -> u8 {
    ((i32::from(value) + 32768) >> 8) as u8
}

/// The d-pad as the device's hat: 0 is up, counting clockwise in eighths, 8
/// is released. Opposite directions held together cancel, as on the real
/// d-pad they cannot both be.
fn hat(buttons: u32) -> u8 {
    let held = |bit| i8::from(buttons & bit != 0);
    let x = held(button::DPAD_RIGHT) - held(button::DPAD_LEFT);
    let y = held(button::DPAD_DOWN) - held(button::DPAD_UP);
    match (x, y) {
        (0, -1) => 0,
        (1, -1) => 1,
        (1, 0) => 2,
        (1, 1) => 3,
        (0, 1) => 4,
        (-1, 1) => 5,
        (-1, 0) => 6,
        (-1, -1) => 7,
        _ => 8,
    }
}

/// The input report for `state`. `counter` wraps at 64; `clock` is the
/// sensor clock (see [`sensor_ticks`]).
pub fn input_report(state: &PadState, counter: u8, clock: u16) -> [u8; INPUT_LEN] {
    let b = state.buttons;
    let bit = |mask, value| if b & mask != 0 { value } else { 0 };
    let left_trigger = (state.left_trigger >> 8) as u8;
    let right_trigger = (state.right_trigger >> 8) as u8;

    let mut r = [0u8; INPUT_LEN];
    r[0] = 0x01;
    r[1] = stick(state.left_x);
    r[2] = stick(state.left_y);
    r[3] = stick(state.right_x);
    r[4] = stick(state.right_y);
    r[5] = hat(b)
        | bit(button::WEST, 0x10)
        | bit(button::SOUTH, 0x20)
        | bit(button::EAST, 0x40)
        | bit(button::NORTH, 0x80);
    // The trigger bits are set by any pull at all, as the device sets them.
    let l2 = if b & button::LEFT_TRIGGER != 0 || left_trigger > 0 {
        0x04
    } else {
        0
    };
    let r2 = if b & button::RIGHT_TRIGGER != 0 || right_trigger > 0 {
        0x08
    } else {
        0
    };
    r[6] = bit(button::LEFT_SHOULDER, 0x01)
        | bit(button::RIGHT_SHOULDER, 0x02)
        | l2
        | r2
        | bit(button::SELECT, 0x10)
        | bit(button::START, 0x20)
        | bit(button::LEFT_STICK, 0x40)
        | bit(button::RIGHT_STICK, 0x80);
    r[7] = bit(button::MODE, 0x01) | ((counter & 0x3f) << 2);
    r[8] = left_trigger;
    r[9] = right_trigger;
    r[10..12].copy_from_slice(&clock.to_le_bytes());
    // Gyro still, and the accelerometer reading one g on the axis gravity
    // pulls along with the controller lying flat: a controller at rest, which
    // is all the client can say about its motion.
    r[21..23].copy_from_slice(&8192i16.to_le_bytes());
    // On the cable, battery full.
    r[30] = 0x1b;
    // One touch report, both fingers lifted: the high bit of a point's
    // first byte marks it inactive.
    r[33] = 1;
    r[35] = 0x80;
    r[39] = 0x80;
    r
}

